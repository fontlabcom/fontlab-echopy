# this_file: src/fontlab_echopy/tooling/llms.py
"""Write a compact ``llms.txt`` index of the shipped native API declarations.

The index lists, per native module, each class with a one-line summary and
each module-level function with its parameter list. It is read by language
models that need the shape of the API without the full ``.pyi`` stubs.
PythonQt is omitted: it is large and documented upstream.
"""

from __future__ import annotations

import ast
import re
from pathlib import Path

from .merge import is_placeholder_lead

MODULES = ("fontlab", "fontgate", "fontpr", "FL")
SUMMARY_LIMIT = 110
HEADER = """# FontLab Python API (echopy index)

> Classes and functions of FontLab's embedded `fontlab`, `fontgate`, `fontpr` and `FL` modules.
> Generated by fontlab-echopy from its documented stubs; each class line gives a one-line summary.
> Full docstrings and signatures: the `fontlab_echopy/*.pyi` files of the fontlab-echopy package.
> Install fontlab-echopy outside FontLab for completion; inside FontLab the native modules are used.
"""


def summary(node: ast.AST) -> str:
    """First sentence of a docstring, skipping inheritance and C++ signature lines."""
    doc = ast.get_docstring(node) or ""  # type: ignore[arg-type]
    for paragraph in doc.split("\n\n"):
        text = re.sub(r"={3,}|\*\*", "", " ".join(paragraph.split())).strip()
        text = text.removeprefix("Supplemental documentation:").strip()
        if (
            is_placeholder_lead(text)
            or text.endswith(" representation")
            or text.startswith("list of ")
        ):
            continue
        if not text or text.startswith(
            (
                "Inherits from",
                "Constructors:",
                "Native bases:",
                "Captured native MRO:",
                "Native __new__ allocation evidence",
                "Source:",
                "#",
            )
        ):
            continue
        if (
            "(" in text.split(" ", 1)[0]
            or text.endswith(")")
            and " " not in text.rstrip(")").split("(")[0].strip()
        ):
            continue  # a bare C++ signature such as "bool fix()"
        sentence = text.split(". ", 1)[0].rstrip(".")
        if len(sentence) > SUMMARY_LIMIT:
            sentence = sentence[: SUMMARY_LIMIT - 1].rsplit(" ", 1)[0] + "…"
        return sentence
    return ""


def signature(node: ast.FunctionDef) -> str:
    args = ast.unparse(node.args)
    if args == "*args: Any, **kwargs: Any":
        args = "..."
    return f"{node.name}({args})"


def module_lines(path: Path, module: str) -> list[str]:
    tree = ast.parse(path.read_text())
    lines = [f"## {module}", ""]
    lead = summary(tree)
    if lead:
        lines += [lead + ".", ""]
    classes = [
        n
        for n in tree.body
        if isinstance(n, ast.ClassDef) and not n.name.startswith("_")
    ]
    functions = [
        n
        for n in tree.body
        if isinstance(n, ast.FunctionDef) and not n.name.startswith("_")
    ]
    for cls in sorted(classes, key=lambda n: n.name.lower()):
        text = summary(cls)
        lines.append(f"- {cls.name}: {text}" if text else f"- {cls.name}")
    if functions:
        lines.append("")
        lines += [
            f"- {signature(fn)}"
            for fn in sorted(functions, key=lambda n: n.name.lower())
        ]
    return lines + [""]


def render(package: Path) -> str:
    parts = [HEADER]
    for module in MODULES:
        path = package / f"{module}.pyi"
        if path.exists():
            parts.append("\n".join(module_lines(path, module)))
    return "\n".join(parts).rstrip() + "\n"


def write(package: Path, output: Path) -> int:
    """Write the index and return its size in bytes."""
    text = render(package)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text)
    return len(text.encode())
